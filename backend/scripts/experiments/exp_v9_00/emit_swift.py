"""Write `Priors.generated.swift` for Nadir's `Sources/ApneaCore/Learning` (types in
PriorTypes.swift).

Usage (from backend/):
    uv run python scripts/experiments/exp_v9_00/emit_swift.py --nhanes-cache <dir> [--out <path>]
"""

from pathlib import Path

from evaluate import cli, run
from scipy import stats

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE / "out" / "Priors.generated.swift"
MODE_CASE = {"full": ".full", "frc": ".frc", "rv": ".rv"}


def num(x):
    if isinstance(x, bool):
        return "true" if x else "false"
    x = float(x)
    return repr(int(x)) if x.is_integer() and abs(x) < 1e15 else repr(x)


def arr(xs):
    return "[" + ", ".join(num(x) for x in xs) + "]"


def mat(rows, indent):
    if not rows:
        return "[]"
    pad = " " * indent
    return "[\n" + "".join(f"{pad}    {arr(r)},\n" for r in rows) + f"{pad}]"


def kinds(d):
    return "[" + ", ".join(f".{k}: {v}" for k, v in d.items()) + "]"


def task(t):
    prim = "nil" if t["primary"] is None else f".{t['primary']}"
    rho = lambda x: "nil" if x is None else num(x)  # noqa: E731
    return (
        f".init(\n            enough: {kinds(t['enough'])}, keep: {kinds(t['keep'])},\n"
        f"            primary: {prim}, rhoEnough: {rho(t['rhoEnough'])}, rhoKeep: "
        f"{rho(t['rhoKeep'])}\n        )"
    )


def t90_table():
    return [float(stats.t.ppf(0.9, df)) for df in range(1, 31)]


def swift(r, export_name):
    lines = [
        "// Generated by spo2-modelling backend/scripts/experiments/exp_v9_00/emit_swift.py from",
        f"// {export_name}, the 21 February 2026 STAmina CSV and NHANES 2007-2012. Do not edit "
        "by hand:",
        "// rerun the harness (exp_v9_00_results.txt says where each number comes from).",
        "//",
        f"// Evidence floors: {r['calibration']['header']}.",
        "",
        "import Foundation",
        "",
        "enum Priors {",
        "    /// `scipy.stats.t.ppf(0.9, df)` for df 1 to 30; index 0 is df 1.",
        "    static let t90: [Double] = [",
    ]
    t = t90_table()
    for i in range(0, 30, 4):
        lines.append("        " + ", ".join(repr(x) for x in t[i : i + 4]) + ",")
    lines.append("    ]")
    lines.append("")
    mu0, k0, a0, b0 = r["delay_prior"]
    lines.append(
        "    /// Data-informed: mu0 is the mean of every session's mean onset across both "
        "oximeters, "
        "beta0 the\n    /// pooled between-session variance (alpha0 = 2, kappa0 = 2)."
    )
    lines.append(
        f"    static let postHoldDelay = PostHoldDelayPrior(mu0: {num(mu0)}, kappa0: {num(k0)}, "
        f"alpha0: {num(a0)}, beta0: {num(b0)})"
    )
    lines.append("")
    hv = r["hold_volume"]
    if hv["model"] is None:
        lines.append(
            "    /// No abstention band reached 90 % accuracy at 50 % coverage: no adopted model."
        )
        lines.append("    static let holdVolume: HoldVolumePrior? = nil")
    else:
        m, (lo, hi) = hv["model"], hv["band"]
        lab = hv["labelled"]
        lines += [
            "    /// Laplace logistic on the 15 features; band chosen leave-one-session-out.",
            "    static let holdVolume: HoldVolumePrior? = HoldVolumePrior(",
            f"        featureMeans: {arr(m['means'])},",
            f"        featureScales: {arr(m['scales'])},",
            f"        mean: {arr(m['mean'])},",
            f"        covariance: {mat(m['cov'].tolist(), 8)},",
            f"        lowerBand: {num(lo)},",
            f"        upperBand: {num(hi)},",
            f'        labelled: ["full": {lab["full"]}, "rv": {lab["rv"]}, "frc": {lab["frc"]}]',
            "    )",
        ]
    lines.append("")
    sp = r["spirometry"]
    if sp is None:
        lines.append("    static let spirometry: SpirometryReference? = nil")
        lines.append("    static let staticVolumes: StaticVolumeRatios? = nil")
        lines.append("    static let oxygenStore: OxygenStoreConstants? = nil")
    else:

        def eq(e):
            return (
                ".init("
                + ", ".join(f"{k}: {num(e[k])}" for k in ("a0", "a1", "a2", "a3", "c0", "c1"))
                + ")"
            )

        def per_sex(s):
            p = sp[s]
            h0, h1 = p["heightRange"]
            return (
                f".init(\n            fvc: {eq(p['fvc'])},\n            fev1: {eq(p['fev1'])},\n"
                f"            heightRange: {num(h0)}...{num(h1)}\n        )"
            )

        a0_, a1_ = sp["ageRange"]
        lines += [
            "    /// NHANES 2007-2010 never-smokers, grades A/B, ages 20-79; tested on 2011-2012.",
            "    static let spirometry: SpirometryReference? = SpirometryReference(",
            f"        male: {per_sex('male')},",
            f"        female: {per_sex('female')},",
            f"        ageRange: {num(a0_)}...{num(a1_)}",
            "    )",
            "",
        ]
        rt = r["ratios"]

        def line(x):
            return f".init(r0: {num(x[0])}, r1: {num(x[1])})"

        def ratio_sex(s):
            p = rt[s]
            return (
                f".init(vcOverTLC: {line(p['vcOverTLC'])}, frcOverTLC: {line(p['frcOverTLC'])}, "
                f"rvOverTLC: {line(p['rvOverTLC'])})"
            )

        lines += [
            "    /// ECSC/ERS 1993 (Quanjer et al.) RV/TLC and FRC/TLC; VC/TLC = 1 − RV/TLC. "
            "Log SDs derived.",
            "    static let staticVolumes: StaticVolumeRatios? = StaticVolumeRatios(",
            f"        ageFloor: {num(rt['ageFloor'])},",
            f"        ageRange: {num(rt['ageRange'][0])}...{num(rt['ageRange'][1])},",
            f"        male: {ratio_sex('male')},",
            f"        female: {ratio_sex('female')},",
            f"        tlcLogSD: {num(rt['tlcLogSD'])},",
            f"        frcLogSD: {num(rt['frcLogSD'])},",
            f"        rvLogSD: {num(rt['rvLogSD'])}",
            "    )",
            "",
        ]
        c = r["oxygen_store"]

        def o2_sex(s):
            p = c[s]
            return (
                ".init("
                + ", ".join(
                    f"{k}: {num(p[k])}"
                    for k in (
                        "haemoglobinGdL",
                        "nadlerK1",
                        "nadlerK2",
                        "nadlerK3",
                        "muscleFraction",
                    )
                )
                + ")"
            )

        top = (
            "btpsToStpd",
            "fAO2Start",
            "fAO2End",
            "arterialFraction",
            "arterialSaturationStart",
            "arterialSaturationEnd",
            "venousSaturationStart",
            "venousSaturationEnd",
            "hufner",
        )
        tail = (
            "myoglobinPerKgMuscle",
            "myoglobinO2PerGram",
            "myoglobinUsableFraction",
            "restingVO2PerKg",
            "diveReflexFactor",
            "sigmaMC",
            "sigmaMCPersonalised",
            "sigmaFloor",
        )
        lines += [
            "    /// From the harness's literature.py (statuses in exp_v9_00_results.txt); "
            "saturations from",
            "    /// the Severinghaus ODC; arterialFraction reproduces the Monte Carlo median "
            "blood store.",
            "    static let oxygenStore: OxygenStoreConstants? = OxygenStoreConstants(",
            *[f"        {k}: {num(c[k])}," for k in top],
            f"        male: {o2_sex('male')},",
            f"        female: {o2_sex('female')},",
            *[f"        {k}: {num(c[k])}," for k in tail[:-1]],
            f"        {tail[-1]}: {num(c[tail[-1]])}",
            "    )",
        ]
    lines.append("")
    cfg = r["hold_model"]["config"]
    hl = "nil" if cfg["halfLifeDays"] is None else num(cfg["halfLifeDays"])
    names = lambda xs: "[" + ", ".join(f'"{x}"' for x in xs) + "]"  # noqa: E731
    ratios = ", ".join(f"{MODE_CASE[k]}: {num(v)}" for k, v in cfg["placeholderRatios"].items())
    lines += [
        "    /// Inputs, coefficients and half-life chosen by the forward chain; σ² prior is "
        "harness judgement.",
        "    static let holdModel = HoldModelPrior(",
        f"        covariates: {names(cfg['covariates'])},",
        f"        beta: {arr(cfg['beta'])},",
        f"        betaCovariance: {mat(cfg['betaCov'], 8)},",
        f"        axes: {names(cfg['axes'])},",
        f"        gamma: {arr(cfg['gamma'])},",
        f"        gammaCovariance: {mat(cfg['gammaCov'], 8)},",
        f"        halfLifeDays: {hl},",
        f"        sigmaA0: {num(cfg['sigmaA0'])},",
        f"        sigmaB0: {num(cfg['sigmaB0'])},",
        f"        placeholderRatios: [{ratios}],",
        f"        placeholderLogSD: {num(cfg['placeholderLogSD'])},",
        f"        personalisePhysiology: {num(cfg['personalisePhysiology'])}",
        "    )",
        "",
    ]
    f = r["calibration"]["floors"]
    lines.append("    static let evidence = EvidenceFloors(")
    order = ("delay", "holdVolume", "spirometry", "oxygenStore", "axis", "pb", "level", "readiness")
    lines += [f"        {k}: {task(f[k])}{',' if k != order[-1] else ''}" for k in order]
    lines.append("    )")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    p = cli()
    p.add_argument("--out", default=str(DEFAULT_OUT))
    a = p.parse_args()
    import json

    r = run(
        a.export,
        a.stamina,
        a.nhanes_cache,
        json.loads(a.profile) if a.profile else None,
        write=False,
    )
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(swift(r, Path(a.export).name))
    print(f"wrote {out}")
